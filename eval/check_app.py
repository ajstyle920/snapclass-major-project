"""Run the app's real face pipeline on the benchmark dataset.

    python eval/check_app.py

`src/pipelines/face_pipeline.py` is imported unchanged. Only the database is
replaced: `get_all_students()` returns students built from dataset photos
instead of rows from Supabase. This checks that the code the app runs gives
the results the benchmark reports.

Needs the app's own requirements (streamlit) in addition to requirements-eval.txt.

Checks
------
1. Matching function: `match_face` makes the same decision as the benchmark's
   nearest-neighbour matching on every probe, and at threshold 0.6 the same
   decision the v1 SVM made (so removing the SVM changed nothing by itself).
2. Registration and login: students are registered through `get_face_embeddings`,
   then every probe photo of one test split goes through `predict_attendance`.
3. Classroom photos: `predict_attendance` on the 20 composite photos reproduces
   the benchmark's v2 numbers.
4. New registration: a new student is recognised only after `refresh_face_index`,
   and the dlib models are not reloaded.
5. Edge cases: no students, and exactly one student (which needed a special case
   when the app used an SVM).
"""
import sys
import types

import numpy as np
from PIL import Image as PILImage

from common import (EVAL_DIR, GROUP_DIR, RESULTS_DIR, SEEDS, enrollment_candidates, identity_halves,
                    list_images, load_cache, load_json, make_gallery)
from evaluate import V1_THRESHOLD, V2_THRESHOLD, identify
from models import RECOGNITION_MODELS

sys.path.insert(0, str(EVAL_DIR.parent))

# --- replace the Supabase-backed module with an in-memory student table ---------------------
FAKE_DB: list[dict] = []
fake_db_module = types.ModuleType("src.database.db")
fake_db_module.get_all_students = lambda: list(FAKE_DB)
sys.modules["src.database.db"] = fake_db_module

from src.pipelines import face_pipeline  # noqa: E402  (the app's real module)
from src.pipelines.face_matching import FACE_MATCH_THRESHOLD, match_face  # noqa: E402

lines = ["# App checks", "", "Generated by `eval/check_app.py`, which runs the app's real "
         "`src/pipelines/face_pipeline.py` on the benchmark dataset with the database replaced by "
         "dataset students.", ""]


def report(name, ok, detail):
    lines.append(f"- {'✅' if ok else '❌'} **{name}**: {detail}")
    print(("PASS  " if ok else "FAIL  ") + name + " — " + detail, flush=True)
    assert ok, name


def load_rgb(path):
    return np.array(PILImage.open(path).convert("RGB"))


def register(subject_ids, enroll, by_id):
    """Register students the way student_screen.py does: first face embedding of the photo, as a list."""
    FAKE_DB.clear()
    for number, subject in enumerate(subject_ids, start=1):
        encodings = face_pipeline.get_face_embeddings(load_rgb(by_id[enroll[subject]].path))
        FAKE_DB.append({"student_id": number, "name": subject, "face_embedding": encodings[0].tolist()})
    return {subject: number for number, subject in enumerate(subject_ids, start=1)}


def main():
    images = list_images()
    by_id = {i.image_id: i for i in images}
    cache = load_cache("dlib_hog")
    candidates = enrollment_candidates(RECOGNITION_MODELS)
    assert FACE_MATCH_THRESHOLD == V2_THRESHOLD

    # 1. matching function vs benchmark, on all 10 test runs ---------------------------------
    n = same_nn = same_v1 = 0
    for seed in SEEDS:
        for half in identity_halves(seed):
            known, unknown, enroll = make_gallery(half, seed, candidates)
            gallery = np.stack([cache[enroll[s]]["embedding"] for s in known])
            nn = identify("dlib_hog", cache, known, unknown, enroll, "nn")
            svm = identify("dlib_hog", cache, known, unknown, enroll, "svm")
            for (_, a), (_, b) in zip(nn.iterrows(), svm.iterrows()):
                emb = cache[a.image_id]["embedding"]
                got, _ = match_face(emb, gallery, known)                      # app default threshold
                want = a.pred if a.dist <= V2_THRESHOLD else None
                got_06, _ = match_face(emb, gallery, known, threshold=V1_THRESHOLD)
                want_06 = b.pred if b.dist <= V1_THRESHOLD else None          # what v1's SVM rule decided
                n += 1
                same_nn += got == want
                same_v1 += got_06 == want_06
    report("Matching function equals the benchmark", same_nn == n,
           f"`match_face` gave the benchmark's decision on {same_nn}/{n} probes at threshold {V2_THRESHOLD}")
    report("Removing the SVM changed no decision", same_v1 == n,
           f"at threshold {V1_THRESHOLD}, `match_face` gave the same decision as the v1 SVM rule on {same_v1}/{n} probes")

    # 2. registration + login through the real pipeline, one full test split -----------------
    half = identity_halves(0)[1]
    known, unknown, enroll = make_gallery(half, 0, candidates)
    ids = register(known, enroll, by_id)
    drift = max(float(np.abs(np.array(s["face_embedding"]) - cache[enroll[s["name"]]]["embedding"]).max())
                for s in FAKE_DB)
    report("Registration embeddings equal the benchmark's", drift < 1e-9,
           f"{len(FAKE_DB)} students registered through `get_face_embeddings`; largest difference {drift:.1e}")
    assert face_pipeline.refresh_face_index()

    expected = identify("dlib_hog", cache, known, unknown, enroll, "nn")
    agree = correct = strangers_in = known_n = unknown_n = 0
    for _, row in expected.iterrows():
        detected, all_ids, num_faces = face_pipeline.predict_attendance(load_rgb(by_id[row.image_id].path))
        want = {ids[row.pred]} if row.dist <= V2_THRESHOLD else set()
        # photos with extra false detections can add ids; compare on single-face photos, count the rest
        got = set(detected)
        agree += (got == want) if num_faces == 1 else (want <= got)
        if row.is_known:
            known_n += 1
            correct += ids[row.true] in got
        else:
            unknown_n += 1
            strangers_in += bool(got)
    report("Login decisions equal the benchmark", agree == len(expected),
           f"`predict_attendance` matched the benchmark on {agree}/{len(expected)} photos of one test split "
           f"({correct}/{known_n} registered students recognised, {strangers_in}/{unknown_n} stranger photos accepted)")

    # 3. composite classroom photos ----------------------------------------------------------
    meta = load_json(GROUP_DIR / "groups.json")
    ids = register(meta["known"], meta["enroll"], by_id)
    assert face_pipeline.refresh_face_index()
    present_n = marked_n = false_n = 0
    for photo in meta["photos"]:
        detected, _, _ = face_pipeline.predict_attendance(load_rgb(GROUP_DIR / photo["file"]))
        present = {ids[t["subject"]] for t in photo["tiles"] if t["subject"] in ids}
        present_n += len(present)
        marked_n += len(set(detected) & present)
        false_n += len(set(detected) - present)
    import pandas as pd
    bench = pd.read_csv(RESULTS_DIR / "group_photos_summary.csv")
    bench = bench[bench.pipeline.str.contains("v2 app")]
    ok = (marked_n, present_n, false_n) == (int(bench.marked_correctly.sum()), int(bench.students_present.sum()),
                                           int(bench.false_present.sum()))
    report("Classroom photos equal the benchmark", ok,
           f"`predict_attendance` on 20 composite photos: {marked_n}/{present_n} present students marked "
           f"present, {false_n} wrongly marked present (benchmark v2: {int(bench.marked_correctly.sum())}/"
           f"{int(bench.students_present.sum())}, {int(bench.false_present.sum())})")

    # 4. a new registration is picked up, without reloading the models -----------------------
    newcomer = meta["unknown"][0]
    photos = [i for i in images if i.subject == newcomer]
    models_before = face_pipeline.load_dlib_models()
    FAKE_DB.append({"student_id": 999, "name": newcomer,
                    "face_embedding": face_pipeline.get_face_embeddings(load_rgb(photos[0].path))[0].tolist()})
    before, _, _ = face_pipeline.predict_attendance(load_rgb(photos[0].path))
    face_pipeline.refresh_face_index()
    after, _, _ = face_pipeline.predict_attendance(load_rgb(photos[0].path))
    same_models = all(a is b for a, b in zip(models_before, face_pipeline.load_dlib_models()))
    report("New registration is picked up", 999 not in before and 999 in after and same_models,
           "a newly added student is recognised after `refresh_face_index()`, and the dlib models "
           "stay loaded (same objects before and after)")

    # 5. edge cases --------------------------------------------------------------------------
    FAKE_DB.clear()
    face_pipeline.refresh_face_index()
    detected, all_ids, num_faces = face_pipeline.predict_attendance(load_rgb(photos[0].path))
    empty_ok = (detected, all_ids, num_faces) == ({}, [], 1)
    FAKE_DB.append({"student_id": 7, "name": newcomer,
                    "face_embedding": face_pipeline.get_face_embeddings(load_rgb(photos[0].path))[0].tolist()})
    face_pipeline.refresh_face_index()
    own, _, _ = face_pipeline.predict_attendance(load_rgb(photos[1].path))
    other_person = next(i for i in images if i.subject == meta["unknown"][1])
    other, all_ids, _ = face_pipeline.predict_attendance(load_rgb(other_person.path))
    report("Edge cases", empty_ok and all_ids == [7],
           f"no students: nothing detected and no error; one student: runs without a special case "
           f"(their second photo was {'recognised' if own == {7: True} else 'not recognised'}, "
           f"a different person was {'rejected' if other == {} else 'accepted'})")

    (RESULTS_DIR / "app_checks.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
