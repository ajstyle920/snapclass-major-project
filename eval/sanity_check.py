"""Checks that the evaluation code itself is trustworthy.

    python eval/sanity_check.py

1. Protocol integrity: tune/test people never overlap, registered/unregistered
   people never overlap, enrollment photos are never used as probes.
2. Random embeddings: a "model" that outputs noise must score near zero.
3. Shuffled labels: enrolling every student under another student's name must
   destroy the correct-identification rate.
4. Self-match: probing with the enrollment photo itself must give 100%.
"""
import numpy as np

from common import (KNOWN_PER_HALF, RESULTS_DIR, SEEDS, UNKNOWN_PER_HALF, enrollment_candidates,
                    identity_halves, list_images, load_cache, make_gallery)
from evaluate import META, curve, identify, rates, threshold_grid, tune
from models import RECOGNITION_MODELS

lines = ["# Sanity checks", "", "Generated by `eval/sanity_check.py`.", ""]


def report(name, ok, detail):
    lines.append(f"- {'✅' if ok else '❌'} **{name}**: {detail}")
    print(("PASS  " if ok else "FAIL  ") + name + " — " + detail)
    assert ok, name


def main():
    candidates = enrollment_candidates(RECOGNITION_MODELS)
    images = list_images()
    cache = load_cache("dlib_hog")

    # 1. protocol integrity
    n_runs = 0
    for seed in SEEDS:
        a, b = identity_halves(seed)
        assert not set(a) & set(b) and len(a) == len(b) == 25
        for half in (a, b):
            known, unknown, enroll = make_gallery(half, seed, candidates)
            assert len(known) == KNOWN_PER_HALF and len(unknown) == UNKNOWN_PER_HALF
            assert not set(known) & set(unknown)
            res = identify("dlib_hog", cache, known, unknown, enroll, "nn")
            assert not set(res.image_id) & set(enroll.values())
            per_person = {s: sum(i.subject == s for i in images) for s in half}
            assert res.is_known.sum() == sum(per_person[s] - 1 for s in known)   # all but the enrollment photo
            assert (~res.is_known).sum() == sum(per_person[s] for s in unknown)  # every photo of a stranger
            assert set(res.true) <= set(half)
            n_runs += 1
    report("Protocol integrity", True,
           f"{n_runs} test splits checked: tune/test people disjoint, registered/unregistered disjoint, "
           "enrollment photos excluded from probes, every remaining photo probed exactly once")

    a, b = identity_halves(0)
    tk, tu, te = make_gallery(a, 0, candidates)
    xk, xu, xe = make_gallery(b, 0, candidates)
    grid = threshold_grid(META["dlib_hog"])

    # 2. random embeddings
    rng = np.random.default_rng(0)
    noise = {i.image_id: {"embedding": rng.normal(size=128) * 0.03} for i in images}
    t = tune(curve(identify("dlib_hog", noise, tk, tu, te, "nn"), grid))
    r = rates(identify("dlib_hog", noise, xk, xu, xe, "nn"), t)
    best_possible = max(rates(identify("dlib_hog", noise, xk, xu, xe, "nn"), g)["correct_id"] for g in grid)
    report("Random embeddings score near zero", r["correct_id"] < 0.05 and best_possible < 0.15,
           f"correct identification {r['correct_id']:.1%} at the tuned threshold; "
           f"{best_possible:.1%} at the best possible threshold (chance = 1/18 = 5.6%)")

    # 3. shuffled enrollment labels
    real = rates(identify("dlib_hog", cache, xk, xu, xe, "nn"), 0.6)
    rotated = {s: xe[xk[(i + 1) % len(xk)]] for i, s in enumerate(xk)}
    shuffled_cache = dict(cache)
    res = identify("dlib_hog", shuffled_cache, xk, xu, rotated, "nn")
    res = res[~res.image_id.isin(set(xe.values()))]
    sh = rates(res, 0.6)
    report("Shuffled labels destroy accuracy", sh["correct_id"] < 0.05 < real["correct_id"],
           f"correct identification drops from {real['correct_id']:.1%} to {sh['correct_id']:.1%} "
           "when each student is enrolled with another student's photo")

    # 4. self-match
    gallery = np.stack([cache[xe[s]]["embedding"] for s in xk])
    d = META["dlib_hog"].distance(gallery, gallery)
    report("Self-match is perfect", bool((np.argmin(d, axis=1) == np.arange(len(xk))).all() and np.allclose(np.diag(d), 0)),
           "each enrollment photo is nearest to itself at distance 0")

    (RESULTS_DIR / "sanity_checks.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
